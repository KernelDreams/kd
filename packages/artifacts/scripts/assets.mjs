/**
 * Ассеты dist: prelude моста (как есть) и вендорный React для import map гостя.
 *
 * React — CommonJS: сборка каждой точки входа отдельно дала бы по копии react
 * (хуки ломаются) либо шим `__require("react")`, падающий в браузере. Поэтому
 * все четыре входа собираются ОДИН раз в `_core.js` (esbuild дедуплицирует
 * react), а фасады реэкспортируют из него. Списки экспортов читаются из
 * установленных пакетов — не разъедутся с версией. (Приём exz v1 build-vendor.)
 */
import { build } from 'esbuild'
import { copyFile, mkdir, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import React from 'react'
import ReactDOM from 'react-dom'
import * as ReactDOMClient from 'react-dom/client'
import * as JsxRuntime from 'react/jsx-runtime'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const out = resolve(root, 'dist', 'assets')
const vendor = resolve(out, 'vendor')
await mkdir(vendor, { recursive: true })
await copyFile(resolve(root, 'assets', 'prelude.js'), resolve(out, 'prelude.js'))

await build({
  stdin: {
    contents: `import * as React from 'react'
import * as ReactDOM from 'react-dom'
import * as ReactDOMClient from 'react-dom/client'
import * as JsxRuntime from 'react/jsx-runtime'
export { React, ReactDOM, ReactDOMClient, JsxRuntime }`,
    resolveDir: root,
    sourcefile: '_core.js',
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  outfile: resolve(vendor, '_core.js'),
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'none',
  minify: true,
  logLevel: 'warning',
})

const namesOf = (mod) =>
  Object.keys(mod)
    .filter((k) => k !== 'default' && k !== '__esModule' && /^[A-Za-z_$][\w$]*$/.test(k))
    .sort()
const facade = (binding, mod, withDefault) =>
  [
    '// generated by scripts/assets.mjs — do not edit',
    `import { ${binding} } from './_core.js'`,
    `export const { ${namesOf(mod).join(', ')} } = ${binding}`,
    withDefault ? `export default ${binding}` : '',
    '',
  ]
    .filter((l) => l !== '')
    .join('\n')

await writeFile(resolve(vendor, 'react.js'), facade('React', React, true))
await writeFile(resolve(vendor, 'react-dom.js'), facade('ReactDOM', ReactDOM, true))
await writeFile(resolve(vendor, 'react-dom-client.js'), facade('ReactDOMClient', ReactDOMClient, false))
await writeFile(resolve(vendor, 'react-jsx-runtime.js'), facade('JsxRuntime', JsxRuntime, false))
console.log('dist/assets: prelude.js, vendor/{_core,react,react-dom,react-dom-client,react-jsx-runtime}.js')
