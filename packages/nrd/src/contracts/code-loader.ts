// CodeLoader — контракт загрузки кода из документа (rz-merge §0.5).
//
// Тело `## $fn` / `%fn` — произвольный TS/JS, который хост обязан превратить в
// модуль. На Node это временный файл + `import()`, на Workers — Worker Loader,
// в браузере — blob-URL. Контракт описывает ТОЛЬКО намерение: «вот код, дай
// модуль», — и потому не упоминает ни файловую систему, ни `require`.
//
// Отсутствие capability — ошибка хоста, а не повод для фолбэка: `new Function`
// вместо модуля тихо ломает импорты внутри тела и меняет семантику `export`.

/** Язык тела. Оба исполняются нативным TS ноды — различие декларативное. */
export type CodeLang = 'ts' | 'js'

export interface CodeLoadOptions {
  /** Язык тела; дефолт решает реализация (обычно `ts`). */
  lang?: CodeLang
  /**
   * Имя для стеков и сорсмапов. НЕ обязано существовать: реализация вправе
   * выбрать собственный путь/URL, а это — человекочитаемая метка звена.
   */
  filename?: string
  /**
   * База для резолва импортов кода. Голые импорты (`@kerneldreams/nrd`) и
   * относительные (`./parts/x.ts`) обязаны резолвиться так же, как если бы код
   * лежал файлом здесь. Реализация без понятия «директория» её игнорирует.
   */
  baseDir?: string
}

/** Загруженный модуль: пространство имён экспортов. */
export type LoadedModule = Record<string, unknown>

/**
 * Загрузчик кода. Одна операция, асинхронная (любая реализация асинхронна:
 * динамический импорт, воркер, сеть).
 *
 * @throws реализация обязана ронять с внятной причиной — синтаксис, не
 *   разрешившийся импорт, отказ песочницы. Молчаливый пустой модуль запрещён.
 */
export interface CodeLoader {
  /** Идентификатор реализации — для сообщений об ошибке (`node`, `worker`). */
  readonly id: string
  load(code: string, opts?: CodeLoadOptions): Promise<LoadedModule>
}
